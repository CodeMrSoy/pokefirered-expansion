static bool8 MigrateBoxMon(struct BoxPokemon *mon)
{
    u16 original = GetBoxMonData(mon, MON_DATA_SPECIES);
    u16 species = QuantumCanonicalSpecies(original);
    u16 item = GetBoxMonData(mon, MON_DATA_HELD_ITEM);
    if (species != original) SetBoxMonData(mon, MON_DATA_SPECIES, &species);
    if (ItemIsMail(item))
    {
        item = ITEM_NONE;
        SetBoxMonData(mon, MON_DATA_HELD_ITEM, &item);
    }
    return species != original;
}

void QuantumMigrateLoadedPokemon(void)
{
    u32 i, box;
    for (i = 0; i < PARTY_SIZE; i++)
    {
        if (!GetMonData(&gPlayerParty[i], MON_DATA_SPECIES)) continue;
        if (MigrateBoxMon(&gPlayerParty[i].box)) CalculateMonStats(&gPlayerParty[i]);
        // The old Mail save arrays remain reserved; no save fields are shifted.
        u8 noMail = 255;
        SetMonData(&gPlayerParty[i], MON_DATA_MAIL, &noMail);
    }
    for (box = 0; box < TOTAL_BOXES_COUNT; box++)
        for (i = 0; i < IN_BOX_COUNT; i++) MigrateBoxMon(GetBoxedMonPtr(box, i));
    for (i = 0; i < DAYCARE_MON_COUNT; i++) MigrateBoxMon(&gSaveBlock1Ptr->daycare.mons[i].mon);
    for (i = 0; i < MAX_FUSION_STORAGE; i++)
        if (MigrateBoxMon(&gPokemonStoragePtr->fusions[i].box)) CalculateMonStats(&gPokemonStoragePtr->fusions[i]);
}

// Old PC items and fusion partners remain in their original save slots until
// there is capacity to recover them. Retry whenever tablet storage is opened
// or a Pokemon is released; a full Bag/box must never discard ownership.
void QuantumRecoverStoredItemsAndPokemon(void)
{
    u32 i, box;
    for (i = 0; i < PC_ITEMS_COUNT; i++)
    {
        struct ItemSlot *slot = &gSaveBlock1Ptr->pcItems[i];
        u16 qty = GetPCItemQuantity(&slot->quantity);
        if (slot->itemId && qty && !ItemIsMail(slot->itemId) && AddBagItem(slot->itemId, qty))
            RemovePCItem(slot->itemId, qty);
    }
    for (i = 0; i < MAX_FUSION_STORAGE; i++)
    {
        struct Pokemon *mon = &gPokemonStoragePtr->fusions[i];
        if (!GetMonData(mon, MON_DATA_SPECIES)) continue;
        for (box = 0; box < TOTAL_BOXES_COUNT; box++)
        {
            s16 slot = GetFirstFreeBoxSpot(box);
            if (slot < 0) continue;
            SetBoxMonAt(box, slot, &mon->box);
            ZeroMonData(mon);
            break;
        }
    }
}

