static bool8 RetiredMap(const struct WarpData *warp)
{
    return QuantumIsRetiredMap(warp->mapGroup, warp->mapNum);
}

static void RecoverWarp(struct WarpData *warp)
{
    if (!RetiredMap(warp)) return;
    warp->mapGroup = MAP_GROUP(MAP_PALLET_TOWN);
    warp->mapNum = MAP_NUM(MAP_PALLET_TOWN);
    warp->warpId = WARP_ID_NONE;
    warp->x = 10;
    warp->y = 9;
}

void QuantumRecoverWarpDestination(struct WarpData *warp)
{
    RecoverWarp(warp);
}

void QuantumMigrateLoadedWorld(void)
{
    FieldTools_MigrateInventory();
    u32 readScene, writeScene = 0;
    bool8 relocated;
    VidraMigrateMapIds();
    relocated = RetiredMap(&gSaveBlock1Ptr->location);
    if (relocated)
    {
        gSaveBlock1Ptr->pos.x = 10;
        gSaveBlock1Ptr->pos.y = 9;
        gSaveBlock1Ptr->mapLayoutId = LAYOUT_PALLET_TOWN;
    }
    FlagClear(FLAG_SYS_PC_STORAGE_DISABLED);
    FlagSet(FLAG_HIDE_CINNABAR_BILL);
    FlagSet(FLAG_HIDE_CINNABAR_POKECENTER_BILL);
    // Keep retained recap scenes in chronological order; an unavailable map
    // cannot restore its old scenery or NPC snapshot during playback.
    for (readScene = 0; readScene < QUEST_LOG_SCENE_COUNT; readScene++)
    {
        struct QuestLogScene *scene = &gSaveBlock1Ptr->questLog[readScene];
        struct WarpData warp = { .mapGroup = scene->mapGroup, .mapNum = scene->mapNum };
        if (!scene->startType || RetiredMap(&warp)) continue;
        if (writeScene != readScene) gSaveBlock1Ptr->questLog[writeScene] = *scene;
        writeScene++;
    }
    while (writeScene < QUEST_LOG_SCENE_COUNT)
        memset(&gSaveBlock1Ptr->questLog[writeScene++], 0, sizeof(struct QuestLogScene));
    RecoverWarp(&gSaveBlock1Ptr->location);
    RecoverWarp(&gSaveBlock1Ptr->continueGameWarp);
    RecoverWarp(&gSaveBlock1Ptr->dynamicWarp);
    RecoverWarp(&gSaveBlock1Ptr->lastHealLocation);
    RecoverWarp(&gSaveBlock1Ptr->escapeWarp);
    if (relocated)
    {
        // Force a fresh field load instead of restoring retired NPC snapshots.
        gSaveBlock1Ptr->continueGameWarp = gSaveBlock1Ptr->location;
        SetContinueGameWarpStatus();
    }
}
