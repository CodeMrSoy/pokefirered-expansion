#!/usr/bin/env python3
"""Generate indexed GBA tiles for the glass TM card and its sliding case."""
from pathlib import Path
import struct
from PIL import Image
root=Path(__file__).resolve().parents[1]
card=[[0]*32 for _ in range(32)]
def rect(a,c,x,y,w,h):
 for yy in range(y,y+h):a[yy][x:x+w]=[c]*w
# SD silhouette: clipped upper-right corner, side notch and recessed label.
for y in range(3,26):
 for x in range(6,26):
  if x>21 and y<3+x-21:continue
  if x==6 and 10<=y<=13:continue
  card[y][x]=1
for y in range(4,25):
 for x in range(7,25):
  if x>20 and y<4+x-20:continue
  if x==7 and 10<=y<=13:continue
  card[y][x]=3 if x<23 else 7
rect(card,2,8,5,12,1)
rect(card,12,9,12,13,8);rect(card,5,10,13,11,1)
rect(card,1,11,15,7,1);rect(card,1,13,17,7,1)
for x in range(9,23,3):
 rect(card,10,x,7,2,4);rect(card,9,x,7,1,3)
rect(card,13,8,23,15,1)
def pack(a):
 h=len(a);w=len(a[0]);return bytes(a[ty+y][tx+x]|a[ty+y][tx+x+1]<<4 for ty in range(0,h,8) for tx in range(0,w,8) for y in range(8) for x in range(0,8,2))
# Crop at the case slot, rather than hiding the entire card while it moves.
frames=[]
for shift in range(0,21,4):
 a=[[0]*32 for _ in range(32)]
 for y in range(22):
  if y>=shift:a[y]=card[y-shift][:]
 frames.append(pack(a))
# Reassemble the existing TM case tilemap, retaining its indexed artwork.
source=Image.open(root/'graphics/tm_case/tm_case.png')
map_data=(root/'graphics/tm_case/tm_case.bin').read_bytes()
map_tiles=struct.unpack('<1024H',map_data)
def source_pixel(x,y):
 tile=map_tiles[y//8*32+x//8];xx=x%8;yy=y%8
 if tile&1024:xx=7-xx
 if tile&2048:yy=7-yy
 return source.getpixel(((tile&1023)%8*8+xx,(tile&1023)//8*8+yy))
# Square the original curved front into a straight 32-pixel cartridge case.
# The original golden shell, ribbing, gray rim and palette are preserved.
case=[[0]*40 for _ in range(24)]
rect(case,15,3,0,34,24)
rect(case,8,4,1,32,13);rect(case,7,5,2,30,12)
rect(case,6,8,3,24,11);rect(case,15,10,3,20,11)
rect(case,14,4,13,32,1)
for row in range(9):
 sy=70+row*10//9
 xs=[x for x in range(8,60) if source_pixel(x,sy) in (10,11,12,13,14)]
 left,right=min(xs),max(xs)
 for x in range(32):case[14+row][4+x]=source_pixel(left+x*(right-left)//31,sy)
rect(case,10,4,22,32,1)
# Reuse the original gray/yellow upright walls beside the SD-width opening.
for y in range(3,13):
 for x in range(4,10):case[y][x]=source_pixel(12+(x-4),60+(y-3)//2)
 for x in range(30,36):case[y][x]=case[y][39-x]
palette=source.getpalette()[:48]
colors=[(palette[i]>>3)|((palette[i+1]>>3)<<5)|((palette[i+2]>>3)<<10) for i in range(0,48,3)]
out='// Generated by tools/compile_pokeglass_tm_cards.py. Do not edit.\n'
for name,data in [('sGlassTMCardGfx',b''.join(frames)),('sGlassTMCardCaseGfx',pack(case))]:
 out+='static const u32 '+name+'[] = {\n'
 words=[int.from_bytes(data[i:i+4],'little') for i in range(0,len(data),4)]
 for i in range(0,len(words),8):out+='    '+', '.join(f'0x{x:08X}' for x in words[i:i+8])+',\n'
 out+='};\n'
out+='static const u16 sGlassTMCasePalette[] = {\n    '+', '.join(f'0x{x:04X}' for x in colors)+',\n};\n'
(root/'src/data/poke_glass_tm_cards.h').write_text(out,encoding='utf-8')
print('Generated six card positions and the glass TM case')
