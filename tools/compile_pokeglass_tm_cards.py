#!/usr/bin/env python3
"""Generate indexed GBA tiles for the glass TM card and its sliding case."""
from pathlib import Path
import struct
from PIL import Image
root=Path(__file__).resolve().parents[1]
card=[[0]*32 for _ in range(32)]
def rect(a,c,x,y,w,h):
 for yy in range(y,y+h):a[yy][x:x+w]=[c]*w
# SD silhouette: clipped upper-right corner, side notch and recessed label.
for y in range(3,26):
 for x in range(6,26):
  if x>21 and y<3+x-21:continue
  if x==6 and 10<=y<=13:continue
  card[y][x]=1
for y in range(4,25):
 for x in range(7,25):
  if x>20 and y<4+x-20:continue
  if x==7 and 10<=y<=13:continue
  card[y][x]=3 if x<23 else 7
rect(card,2,8,5,12,1)
rect(card,12,9,12,13,8);rect(card,5,10,13,11,1)
rect(card,1,11,15,7,1);rect(card,1,13,17,7,1)
for x in range(9,23,3):
 rect(card,10,x,7,2,4);rect(card,9,x,7,1,3)
rect(card,13,8,23,15,1)
def pack(a):
 h=len(a);w=len(a[0]);return bytes(a[ty+y][tx+x]|a[ty+y][tx+x+1]<<4 for ty in range(0,h,8) for tx in range(0,w,8) for y in range(8) for x in range(0,8,2))
# Crop at the case slot, rather than hiding the entire card while it moves.
frames=[]
for shift in range(0,21,4):
 a=[[0]*32 for _ in range(32)]
 for y in range(32):
  for x in range(32):
   # The front lip rises toward the right in the three-quarter view.
   lip=23-(x-6)*7//20
   if y>=shift and y<lip:a[y][x]=card[y-shift][x]
 frames.append(pack(a))
# Reassemble the existing TM case tilemap, retaining its indexed artwork.
source=Image.open(root/'graphics/tm_case/tm_case.png')
map_data=(root/'graphics/tm_case/tm_case.bin').read_bytes()
map_tiles=struct.unpack('<1024H',map_data)
def source_pixel(x,y):
 tile=map_tiles[y//8*32+x//8];xx=x%8;yy=y%8
 if tile&1024:xx=7-xx
 if tile&2048:yy=7-yy
 return source.getpixel(((tile&1023)%8*8+xx,(tile&1023)//8*8+yy))
# A rectangular cartridge case seen from the same three-quarter angle as the
# original. Keep the original shell's gold texture, rim colors and deep outline.
case=[[0]*40 for _ in range(24)]
def line(c,x0,y0,x1,y1):
 dx=abs(x1-x0);sx=1 if x0<x1 else -1;dy=-abs(y1-y0);sy=1 if y0<y1 else -1;err=dx+dy
 while True:
  if 0<=x0<40 and 0<=y0<24:case[y0][x0]=c
  if x0==x1 and y0==y1:break
  e=2*err
  if e>=dy:err+=dy;x0+=sx
  if e<=dx:err+=dx;y0+=sy
def polygon(c,points):
 for y in range(24):
  for x in range(40):
   cross=[(b[0]-a[0])*(y-a[1])-(b[1]-a[1])*(x-a[0]) for a,b in zip(points,points[1:]+points[:1])]
   if all(v>=0 for v in cross) or all(v<=0 for v in cross):case[y][x]=c
# Thick raised back rim and a recessed, angled cavity; the selected card rises
# through this opening instead of being drawn over a flat front rectangle.
polygon(15,[(2,8),(28,0),(36,5),(36,18),(9,23),(2,18)])
polygon(13,[(3,8),(28,1),(35,5),(9,15)])
polygon(8,[(6,8),(28,2),(32,5),(10,13)])
polygon(7,[(8,8),(28,3),(31,5),(11,12)])
polygon(6,[(10,8),(28,4),(30,6),(12,12)])
polygon(15,[(12,9),(28,5),(29,7),(13,12)])
# Dark side face and the lighter front face make the housing visibly thick.
polygon(10,[(3,10),(9,15),(9,22),(3,18)])
polygon(11,[(10,15),(35,6),(35,17),(10,22)])
for x in range(10,36):
 top=15-(x-9)*9//26;bottom=23-(x-9)*5//26
 for y in range(top+1,bottom):
  sy=70+(y-top)*9//max(1,bottom-top)
  color=source_pixel(20+(x-10)*30//25,sy)
  case[y][x]=color if 10<=color<=14 else (12 if y-top<4 else 11)
# Original highlight/shadow colors, with bevels along each visible edge.
line(14,3,8,28,1);line(8,4,10,9,14)
line(13,3,11,3,17);line(10,5,13,5,18)
line(14,9,15,35,6);line(13,10,16,34,8)
line(10,10,21,34,17);line(15,9,23,35,18)
line(10,11,22,34,18);line(15,2,9,2,18)
line(15,2,18,9,23);line(15,36,6,36,18)
palette=source.getpalette()[:48]
colors=[(palette[i]>>3)|((palette[i+1]>>3)<<5)|((palette[i+2]>>3)<<10) for i in range(0,48,3)]
out='// Generated by tools/compile_pokeglass_tm_cards.py. Do not edit.\n'
for name,data in [('sGlassTMCardGfx',b''.join(frames)),('sGlassTMCardCaseGfx',pack(case))]:
 out+='static const u32 '+name+'[] = {\n'
 words=[int.from_bytes(data[i:i+4],'little') for i in range(0,len(data),4)]
 for i in range(0,len(words),8):out+='    '+', '.join(f'0x{x:08X}' for x in words[i:i+8])+',\n'
 out+='};\n'
out+='static const u16 sGlassTMCasePalette[] = {\n    '+', '.join(f'0x{x:04X}' for x in colors)+',\n};\n'
(root/'src/data/poke_glass_tm_cards.h').write_text(out,encoding='utf-8')
print('Generated six card positions and the glass TM case')
