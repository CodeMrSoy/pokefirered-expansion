#!/usr/bin/env python3
"""Generate Classic level overrides from the verified pre-rebalance manifest.

Only levels are emitted. Current trainer sets and wild species/weights remain
shared. Validate every referenced Quantum slot so data edits cannot silently
apply a baseline level to an unrelated new party/table.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'src/data/adventure_levels.h'

def generate():
    plan = json.loads((ROOT / 'tools/progression/story-levels.json').read_text())
    parties = dict(re.findall(r'=== (\w+) ===(.*?)(?==== |\Z)', (ROOT / 'src/data/trainers.party').read_text(), re.S))
    active = set(re.findall(r'\[DIFFICULTY_NORMAL\]\[(TRAINER_\w+)\]', (ROOT / 'src/data/trainers.h').read_text()))
    retired = set(json.loads((ROOT / 'data/quantum/retired_content.json').read_text())['retired_maps'])
    map_names = {json.loads(p.read_text())['id']: p.parent.name for p in (ROOT / 'data/maps').glob('*/map.json')}
    tables = dict(re.findall(r'const struct WildPokemon (\w+)\[\] =\s*\{(.*?)\n\};', (ROOT / 'src/data/wild_encounters.h').read_text(), re.S))
    lines = ['// Generated by tools/progression/generate_adventure_levels.py. Do not edit.',
             '// Baseline: ' + plan['baseline_commit'],
             'struct ClassicTrainerLevels { u8 before[PARTY_SIZE]; u8 quantum[PARTY_SIZE]; };',
             'static const struct ClassicTrainerLevels sClassicTrainerLevels[TRAINERS_COUNT] =', '{']
    for tid, row in sorted(plan['trainers'].items()):
        if tid not in active or row['stage'] == 'eirik':
            continue
        levels = list(map(int, re.findall(r'^Level: (\d+)$', parties[tid], re.M)))
        assert levels == row['after'], (tid, 'Quantum party diverged; update the baseline mapping')
        assert len(levels) == len(row['before']) <= 6
        lines.append('    [' + tid + '] = {{' + ', '.join(map(str, row['before'])) + '}, {' + ', '.join(map(str, levels)) + '}},')
    lines += ['};', '', 'struct ClassicWildLevels { const struct WildPokemon *table; u8 count; u8 levels[12][2]; };']
    suffixes = {'land_mons': 'LandMons', 'water_mons': 'WaterMons', 'rock_smash_mons': 'RockSmashMons', 'fishing_mons': 'FishingMons'}
    rows = []
    for label, row in sorted(plan['wild_encounters'].items()):
        if row['stage'] == 'eirik':
            continue
        for kind, ranges in row['before'].items():
            symbol = label + '_' + suffixes[kind]
            if symbol not in tables:  # Retired maps are deliberately not linked.
                assert map_names[row['map']] in retired, (symbol, 'Missing active table: update the Classic mapping for this generator/config')
                continue
            levels = [list(map(int, pair)) for pair in re.findall(r'\{\s*(\d+),\s*(\d+),', tables[symbol])]
            assert levels == row['after'][kind], (symbol, 'Quantum encounter table diverged')
            assert len(ranges) == len(levels) <= 12
            guard = 'FIRERED' if '_FireRed' in symbol else 'LEAFGREEN' if '_LeafGreen' in symbol else None
            if guard: lines.append('#ifdef ' + guard)
            lines.append('extern const struct WildPokemon ' + symbol + '[];')
            if guard: lines.append('#endif')
            rows.append((symbol, ranges, guard))
    lines += ['static const struct ClassicWildLevels sClassicWildLevels[] =', '{']
    for symbol, ranges, guard in rows:
        if guard: lines.append('#ifdef ' + guard)
        lines.append('    {' + symbol + ', ' + str(len(ranges)) + ', {' + ', '.join('{' + str(a) + ', ' + str(b) + '}' for a,b in ranges) + '}},')
        if guard: lines.append('#endif')
    lines += ['};', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    text = generate()
    if args.check:
        assert OUT.read_text() == text, 'Regenerate adventure_levels.h'
        print('PASS: Classic level overrides match all active baseline party and wild slots')
    else:
        OUT.write_text(text)
