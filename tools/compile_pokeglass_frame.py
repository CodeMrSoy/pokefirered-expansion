#!/usr/bin/env python3
"""Generate the shared full-screen Pokeglass shell and native-app frame."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
pixels=[[13]*240 for _ in range(160)]
def rect(c,x,y,w,h):
 for row in range(y,y+h): pixels[row][x:x+w]=[c]*w
def rounded(c,x,y,w,h,r):
 for yy in range(h):
  for xx in range(w):
   dx=max(r-xx,xx-(w-1-r),0)
   dy=max(r-yy,yy-(h-1-r),0)
   if dx*dx+dy*dy<=r*r: pixels[y+yy][x+xx]=c
# Slightly thicker red-and-white case, matching the Pokeglass item.
pixels=[[0]*240 for _ in range(160)]
rounded(1,0,0,240,160,9)
rounded(12,1,1,238,158,8)
rounded(13,2,2,236,156,7)
for y in range(2,80):
 for x in range(2,238):
  if pixels[y][x]==13: pixels[y][x]=10
rect(11,16,3,86,1)
rect(15,16,156,86,1)
rounded(1,7,8,226,144,4)
rect(4,10,10,220,140)
rect(1,106,3,12,2)
rect(11,108,3,8,1)
rect(1,122,2,5,4)
rect(5,123,3,3,2)
rect(8,124,3,1,1)
rect(15,133,3,2,2)
rounded(9,109,153,22,5,2)
rect(11,114,154,12,1)
rect(9,0,43,2,12)
rect(9,0,60,2,18)
rect(1,2,79,5,2)
rect(1,233,79,5,2)

def pack(tx,ty,frame=False):
 return bytes((0 if frame and 10<=tx*8+x<230 and 10<=ty*8+y<150 else pixels[ty*8+y][tx*8+x]) | ((0 if frame and 10<=tx*8+x+1<230 and 10<=ty*8+y<150 else pixels[ty*8+y][tx*8+x+1])<<4) for y in range(8) for x in range(0,8,2))
shell=b''.join(pack(x,y) for y in range(20) for x in range(30))
tiles=[bytes(32)]; lookup={tiles[0]:0}; tilemap=[]
for y in range(20):
 for x in range(30):
  tile=pack(x,y,True)
  if tile not in lookup: lookup[tile]=len(tiles); tiles.append(tile)
  tilemap.append(0x180+lookup[tile])
assert len(tiles)<=128
glass_tiles=[bytes(32)];glass_lookup={glass_tiles[0]:0};glass_map=[]
for y in range(20):
 for x in range(30):
  raw=bytearray(pack(x,y,True))
  for yy in range(8):
   for xx in range(0,8,2):
    for dx in (0,1):
     if 10<=x*8+xx+dx<230 and 10<=y*8+yy<150:
      index=yy*4+xx//2;shift=dx*4
      raw[index]=(raw[index]&~(15<<shift))|(4<<shift)
  tile=bytes(raw)
  if tile not in glass_lookup:glass_lookup[tile]=len(glass_tiles);glass_tiles.append(tile)
  glass_map.append(0x180+glass_lookup[tile])
assert len(glass_tiles)<=128
out='// Generated by tools/compile_pokeglass_frame.py. Do not edit.\n'
cover=[bytes(32)]
for i in range(0,len(shell),32):
 tile=shell[i:i+32]
 if tile not in cover: cover.append(tile)
for name,raw in [('sTabletCoverTiles',b''.join(cover)),('sTabletFullShellGfx',shell),('sTabletFrameTiles',b''.join(tiles)),('sTabletGlassFrameTiles',b''.join(glass_tiles))]:
 out+='static const u32 '+name+'[] = {\n'
 words=[int.from_bytes(raw[i:i+4],'little') for i in range(0,len(raw),4)]
 for i in range(0,len(words),8): out+='    '+', '.join(f'0x{x:08X}' for x in words[i:i+8])+',\n'
 out+='};\n'
out+='static const u16 sTabletFrameMap[] = {\n'
for i in range(0,len(tilemap),30): out+='    '+', '.join(f'0x{x:03X}' for x in tilemap[i:i+30])+',\n'
out+='};\n'
out+='static const u16 sTabletGlassFrameMap[] = {\n'
for i in range(0,len(glass_map),30):out+='    '+', '.join(f'0x{x:03X}' for x in glass_map[i:i+30])+',\n'
out+='};\n'
(root/'src/data/poke_glass_frame.h').write_text(out,encoding='utf-8')
print('Full-screen shell and frame:',len(tiles),'unique frame tiles')
