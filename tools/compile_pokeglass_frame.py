#!/usr/bin/env python3
"""Compile the unchanged tablet shell into a compact native app frame."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
im=Image.open(root/'graphics/poke_glass_shell.png');assert im.mode=='P' and im.size==(224,144)
p=im.copy()
for y in range(16,112):
 for x in range(16,208):p.putpixel((x,y),0)
tiles=[bytes(32)];lookup={tiles[0]:0};tilemap=[]
for ty in range(18):
 for tx in range(28):
  tile=bytes(p.getpixel((tx*8+x,ty*8+y))|(p.getpixel((tx*8+x+1,ty*8+y))<<4) for y in range(8) for x in range(0,8,2))
  if tile not in lookup:lookup[tile]=len(tiles);tiles.append(tile)
  tilemap.append(0x180+lookup[tile])
assert len(tiles)<=128
raw=b''.join(tiles)
out='// Generated by tools/compile_pokeglass_frame.py from poke_glass_shell.png.\n'
out+='static const u32 sTabletFrameTiles[] = {\n'
words=[int.from_bytes(raw[i:i+4],'little') for i in range(0,len(raw),4)]
for i in range(0,len(words),8):out+='    '+', '.join(f'0x{x:08X}' for x in words[i:i+8])+',\n'
out+='};\nstatic const u16 sTabletFrameMap[] = {\n'
for i in range(0,len(tilemap),28):out+='    '+', '.join(f'0x{x:03X}' for x in tilemap[i:i+28])+',\n'
out+='};\n'
(root/'src/data/poke_glass_frame.h').write_text(out)
print('Compiled exact frame:',len(tiles),'tiles')
