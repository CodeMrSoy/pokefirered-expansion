"""Harbor props drawn at native resolution using the existing FireRed color ramps.

Keep every footprint and palette bank stable; these are visual replacements only.
"""
from PIL import Image, ImageDraw


def harbor_props():
    ink = (64, 72, 104)
    brown, timber, gold = (112, 80, 40), (192, 160, 88), (232, 200, 120)
    cream = (248, 224, 128)
    gray, silver, white = (120, 120, 128), (200, 200, 216), (240, 240, 248)
    blue, blue_light = (72, 128, 192), (112, 184, 240)
    red, red_dark, red_light = (208, 64, 56), (144, 48, 56), (240, 112, 80)
    assets = {}
    def canvas(w, h):
        im = Image.new('RGBA', (w, h))
        return im, ImageDraw.Draw(im)
    def crate(d, x, y):
        d.rectangle((x, y + 3, x + 13, y + 14), fill=brown, outline=ink)
        d.rectangle((x + 1, y + 4, x + 10, y + 13), fill=timber)
        d.rectangle((x + 11, y + 4, x + 12, y + 13), fill=brown)
        d.polygon([(x, y + 3), (x + 3, y), (x + 13, y), (x + 13, y + 3)], fill=gold, outline=ink)
        d.line((x + 2, y + 5, x + 9, y + 12), fill=brown, width=2)
        d.line((x + 2, y + 12, x + 9, y + 5), fill=brown, width=2)
        d.line((x + 1, y + 4, x + 10, y + 4), fill=cream)
        d.point((x + 2, y + 5), fill=ink); d.point((x + 9, y + 12), fill=ink)
    im, d = canvas(16, 16); crate(d, 1, 0); assets['crate'] = (im, 7)
    im, d = canvas(32, 32)
    crate(d, 1, 16); crate(d, 17, 16); crate(d, 9, 2)
    assets['cargo'] = (im, 7)
    im, d = canvas(16, 16)
    d.rounded_rectangle((2, 2, 13, 14), radius=3, fill=timber, outline=ink)
    d.rectangle((11, 5, 12, 11), fill=brown)
    for x in [5, 8]: d.line((x, 6, x, 12), fill=brown)
    d.ellipse((2, 0, 13, 6), fill=gold, outline=ink)
    d.line((5, 2, 10, 2), fill=cream); d.line((4, 4, 11, 4), fill=brown)
    for y in [6, 11]:
        d.line((2, y, 13, y), fill=ink)
        d.line((3, y + 1, 11, y + 1), fill=gray)
        d.point((4, y + 1), fill=silver)
    assets['barrel'] = (im, 7)
    # A compact swivel crane: readable steel frame, pulley and suspended cargo net.
    im, d = canvas(48, 64)
    d.polygon([(4, 54), (20, 54), (23, 58), (23, 62), (2, 62), (2, 58)], fill=gray, outline=ink)
    d.rectangle((5, 54, 20, 57), fill=silver, outline=ink)
    d.rectangle((8, 17, 15, 54), fill=gold, outline=ink)
    d.rectangle((12, 19, 14, 52), fill=timber)
    d.line((9, 20, 9, 51), fill=cream)
    d.polygon([(9, 21), (38, 3), (43, 6), (15, 30)], fill=gold, outline=ink)
    d.line((13, 21, 38, 6), fill=cream)
    for x, y in [(18, 18), (25, 13), (32, 9)]:
        d.line((x, y, x + 3, y + 5), fill=brown)
    d.line((14, 43, 31, 15), fill=ink, width=3)
    d.line((14, 42, 30, 16), fill=timber)
    d.ellipse((35, 1, 44, 10), fill=timber, outline=ink)
    d.ellipse((38, 4, 41, 7), fill=gray, outline=ink)
    d.line((40, 11, 40, 38), fill=ink)
    d.line((41, 12, 41, 36), fill=silver)
    d.line((40, 36, 40, 40, 43, 40, 44, 38), fill=ink, width=2)
    d.polygon([(40, 40), (33, 49), (34, 57), (40, 60), (46, 57), (47, 49)], fill=timber, outline=ink)
    d.line((35, 49, 44, 49), fill=gold)
    for x in [36, 40, 44]: d.line((40, 42, x, 57), fill=brown)
    for y in [50, 54, 57]: d.line((35, y, 45, y), fill=brown)
    d.ellipse((5, 39, 17, 48), fill=gray, outline=ink)
    d.ellipse((8, 41, 14, 46), fill=gold, outline=ink)
    d.line((11, 44, 19, 44, 19, 48), fill=ink, width=2)
    assets['crane'] = (im, 7)
    # White tapered tower, red gallery and simple stepped roof in FireRed perspective.
    im, d = canvas(48, 96)
    d.polygon([(10, 83), (36, 83), (41, 88), (41, 94), (6, 94), (6, 88)], fill=gray, outline=ink)
    d.rectangle((10, 84, 36, 88), fill=silver)
    d.polygon([(15, 36), (32, 36), (36, 86), (11, 86)], fill=white, outline=ink)
    d.polygon([(28, 37), (31, 37), (35, 85), (29, 85)], fill=silver)
    d.line((14, 69, 33, 69), fill=silver)
    d.rectangle((11, 76, 35, 84), fill=silver)
    d.rectangle((20, 48, 26, 59), fill=ink)
    d.rectangle((21, 49, 24, 56), fill=blue)
    d.line((21, 49, 21, 53), fill=blue_light)
    d.line((19, 59, 27, 59), fill=gray)
    d.rectangle((19, 72, 27, 86), fill=ink)
    d.rectangle((20, 73, 26, 84), fill=blue)
    d.rectangle((21, 74, 25, 79), fill=blue_light)
    d.point((25, 82), fill=cream)
    for y in [87, 90, 93]:
        d.rectangle((17, y, 30, y + 1), fill=white)
        d.line((17, y + 2, 30, y + 2), fill=gray)
    d.rectangle((12, 21, 35, 35), fill=red_dark, outline=ink)
    for x in [15, 23, 31]:
        d.rectangle((x, 23, x + 4, 31), fill=blue, outline=ink)
        d.line((x + 1, 24, x + 3, 24), fill=white)
        d.line((x + 1, 25, x + 1, 28), fill=blue_light)
    d.rectangle((9, 34, 38, 38), fill=red, outline=ink)
    d.line((10, 35, 37, 35), fill=red_light)
    for x in [10, 17, 30, 37]: d.line((x, 30, x, 35), fill=ink)
    d.line((10, 30, 37, 30), fill=silver)
    d.polygon([(9, 20), (22, 7), (25, 7), (38, 20), (35, 23), (12, 23)], fill=red, outline=ink)
    d.polygon([(25, 8), (37, 20), (25, 20)], fill=red_dark)
    d.line((12, 19, 22, 9), fill=red_light, width=2)
    d.line((12, 21, 35, 21), fill=red_light)
    d.rectangle((22, 3, 25, 8), fill=ink)
    d.rectangle((23, 2, 24, 5), fill=red_light)
    assets['lighthouse'] = (im, 4)
    # Keep the hooked silhouette, but widen the lantern and give the iron a bevel.
    im, d = canvas(16, 32)
    d.rectangle((3, 6, 5, 27), fill=ink)
    d.line((4, 7, 4, 26), fill=gray)
    d.line((4, 6, 4, 3, 6, 1, 11, 1, 13, 3, 13, 6), fill=ink)
    d.line((6, 2, 10, 2), fill=silver)
    d.polygon([(8, 7), (11, 5), (15, 7), (15, 8), (8, 8)], fill=ink)
    d.line((10, 7, 13, 7), fill=gray)
    d.rectangle((8, 9, 15, 16), fill=ink)
    d.rectangle((9, 10, 13, 14), fill=cream)
    d.line((9, 10, 9, 12), fill=white)
    d.line((12, 10, 12, 14), fill=timber)
    d.rectangle((9, 17, 14, 18), fill=ink)
    d.line((10, 17, 13, 17), fill=gray)
    d.rectangle((2, 27, 6, 28), fill=gray, outline=ink)
    d.rectangle((1, 29, 7, 31), fill=ink)
    d.line((2, 29, 6, 29), fill=silver)
    assets['lamp'] = (im, 8)
    return assets
