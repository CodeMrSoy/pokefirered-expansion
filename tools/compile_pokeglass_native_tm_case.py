#!/usr/bin/env python3
"""Extract the unchanged original case from its native tilemap onto glass."""
from pathlib import Path
import struct
from PIL import Image
root=Path(__file__).resolve().parents[1]
source=Image.open(root/'graphics/tm_case/tm_case.png')
map_tiles=struct.unpack('<1024H',(root/'graphics/tm_case/tm_case.bin').read_bytes())
def pixel(x,y):
 t=map_tiles[y//8*32+x//8];xx=x%8;yy=y%8
 if t&1024:xx=7-xx
 if t&2048:yy=7-yy
 return source.getpixel(((t&1023)%8*8+xx,(t&1023)//8*8+yy))
# The original case has an open upper rim. Keep each scanline's complete
# outlined span, removing only surrounding screen/background/shadow stripes.
w,h=56,40
pixels=[[pixel(8+x,48+y) for x in range(w)] for y in range(h)]
for y,row in enumerate(pixels):
 edge=[x for x,c in enumerate(row) if c not in (0,3,4,8,9)]
 if not edge:pixels[y]=[0]*w;continue
 left,right=min(edge),max(edge)
 pixels[y]=[c if left<=x<=right else 0 for x,c in enumerate(row)]
assert sum(c in range(10,15) for row in pixels for c in row)>200,'Original case span was not detected'
raw=bytes(pixels[ty+y][tx+x]|pixels[ty+y][tx+x+1]<<4 for ty in range(0,h,8) for tx in range(0,w,8) for y in range(8) for x in range(0,8,2))
out='// Generated by tools/compile_pokeglass_native_tm_case.py. Do not edit.\nstatic const u32 sNativeTMCaseGfx[] = {\n'
words=[int.from_bytes(raw[i:i+4],'little') for i in range(0,len(raw),4)]
for i in range(0,len(words),8):out+='    '+', '.join(f'0x{x:08X}' for x in words[i:i+8])+',\n'
out+='};\n'
(root/'src/data/poke_glass_native_tm_case.h').write_text(out,encoding='utf-8')
print('Original case retained:',sum(c!=0 for row in pixels for c in row),'opaque pixels')
